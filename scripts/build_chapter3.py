def parse_faq(text: str) -> list[dict[str, object]]:
    lines = [line.strip() for line in text.splitlines()]
    markers = [
        index
        for index, line in enumerate(lines)
        if line == "Q" and index + 1 < len(lines) and lines[index + 1] == "A"
    ]
    results: list[dict[str, object]] = []

    for marker_position, start in enumerate(markers):
        end = markers[marker_position + 1] if marker_position + 1 < len(markers) else len(lines)
        block = [line for line in lines[start + 2 : end] if line]
        if block and block[0].isdigit():
            block.pop(0)
        if not block:
            continue

        number = marker_position + 1
        title = block.pop(0)
        answer_start = next(
            (index for index, line in enumerate(block) if line.startswith(("･", "․"))),
            None,
        )
        if answer_start is None:
            continue

        question_detail = "\n".join(block[:answer_start]).strip()
        answer_lines = []
        for line in block[answer_start:]:
            if line == "氠瑢" or line.startswith("汤捯"):
                break
            answer_lines.append(line)
            if line.startswith("【관련 부서】"):
                break

        answer = "\n".join(answer_lines).strip()
        combined_answer = (
            f"질문 내용\n{question_detail}\n\n답변\n{answer}" if question_detail else f"답변\n{answer}"
        )
        results.append(
            {
                "id": f"faq-{number}",
                "category": FAQ_CATEGORIES[number],
                "number": number,
                "question": title,
                "answer": combined_answer,
            }
        )

    return results


